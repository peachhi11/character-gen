def _condition(rule: tuple[str, str, int] | str) -> str:
    if isinstance(rule, str):
        return rule
    key, operator, threshold = rule
    return f"{key} {operator} {threshold}"


def _slugify(engine_type: str) -> str:
    return engine_type.lower().replace("-", "_")


